function E:Locale()
    local language=self.db and self.db.language or "auto"
    if language=="auto" then language=self:Call(GetLocale) or "enUS" end
    if language=="enGB" then language="enUS" elseif language=="esMX" then language="esES" end
    return self.translations[language] and language or "enUS"
end
function E:L(key,a,b,c,d)
    local dictionary=self.translations[self:Locale()]
    local text=dictionary[key] or self.translations.enUS[key] or key
    if a~=nil then return string.format(text,a,b,c,d) end
    return text
end
function E:FontKey()
    local locale=self:Locale()
    if locale=="ruRU" or locale=="koKR" or locale=="zhCN" then return "native" end
    local selected=self.db and self.db.font or "native"
    return self.fontPaths[selected] and selected or "native"
end
function E:AvailableFonts()
    local locale=self:Locale()
    if locale=="ruRU" or locale=="koKR" or locale=="zhCN" then return {{"native","Game font"}} end
    return self.fontOptions
end
function E:FontPath()
    local path
    if GameFontNormal then path=self:Call(GameFontNormal.GetFont,GameFontNormal) end
    return self.fontPaths[self:FontKey()] or path or STANDARD_TEXT_FONT or "Fonts\\FRIZQT__.TTF"
end
function E:RegisterFont(widget,size,flags)
    self.fontWidgets=self.fontWidgets or {}
    table.insert(self.fontWidgets,{widget=widget,size=size,flags=flags})
    widget:SetFont(self:FontPath(),size,flags)
end
function E:ApplyFonts()
    for _,entry in ipairs(self.fontWidgets or {}) do entry.widget:SetFont(self:FontPath(),entry.size,entry.flags) end
end
function E:BindText(widget,key)
    if key=="" then widget:SetText(""); return end
    self.localizedText=self.localizedText or {}
    table.insert(self.localizedText,{widget=widget,key=key})
    widget:SetText(self:L(key))
end
function E:Label(parent,key,size)
    local label=self:Text(parent,size); self:BindText(label,key); return label
end
function E:SetLanguage(language)
    self.db.language=(language=="auto" or self.translations[language]) and language or "auto"
    for _,entry in ipairs(self.localizedText or {}) do entry.widget:SetText(self:L(entry.key)) end
    self:ApplyFonts(); self:UpdateRoles(); self:UpdateColors(); self:UpdatePositions()
    if self.minimapButton then self.minimapButton.tip=self:L("Open roles") end
    self:ShowPage(self.window.page or "roles"); self:RefreshUI()
end
